package com.gymsesh.app.data.model

/**
 * The muscle groups GymSesh tracks. The stats pie chart aggregates trained sets
 * over this enum (primary muscle = full weight, secondary = half weight).
 */
enum class MuscleGroup {
    CHEST,
    BACK,
    SHOULDERS,
    BICEPS,
    TRICEPS,
    FOREARMS,
    QUADS,
    HAMSTRINGS,
    GLUTES,
    CALVES,
    ABS,
    TRAPS,
}
